// Generates packages/shared/src/theme/palette-tokens.ts from web/src/index.css. Run after editing a palette.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'web/src/index.css'), 'utf8').replace(/\r\n/g, '\n');
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const IDS = ['cyan', 'blue', 'indigo', 'violet', 'magenta', 'steel', 'jade', 'lime'];

function tokens(re) {
  const body = (css.match(re) || [])[1] || '';
  return new Map([...body.matchAll(/--c-([a-z0-9-]+)\s*:\s*([^;]+);/gi)].map(m => [m[1], m[2].trim()]));
}
const base = tokens(/:root\s*\{([^}]*)\}/);
const lightBase = tokens(/\[data-theme="light"\]\s*\{([^}]*)\}/);
const plain = m => Object.fromEntries([...m].filter(([, v]) => !v.includes('gradient(')));

const out = {};
for (const id of IDS) {
  const dark = id === 'cyan' ? new Map() : tokens(new RegExp(`:root\\[data-palette="${esc(id)}"\\]\\s*\\{([^}]*)\\}`));
  const light = id === 'cyan' ? new Map() : tokens(new RegExp(`:root\\[data-palette="${esc(id)}"\\]\\s*\\[data-theme="light"\\]\\s*\\{([^}]*)\\}`));
  if (id !== 'cyan' && (!dark.size || !light.size)) throw new Error(`palette ${id}: block missing in index.css`);
  out[id] = { dark: plain(new Map([...base, ...dark])), light: plain(new Map([...base, ...lightBase, ...light])) };
}

const file = `// GENERATED by scripts/generate-palette-tokens.cjs from web/src/index.css. Do not edit by hand.
// Keys are the CSS custom properties without the "--c-" prefix. A web test fails if this drifts from the CSS.
import type { Palette, ThemeMode } from './palettes';

export const PALETTE_TOKENS: Record<Palette, Record<ThemeMode, Record<string, string>>> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, 'packages/shared/src/theme/palette-tokens.ts'), file);
console.log('wrote packages/shared/src/theme/palette-tokens.ts');
